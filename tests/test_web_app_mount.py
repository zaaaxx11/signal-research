def test_app_prefix_serves_the_shell(client: TestClient) -> None:
    response = client.get("/app", follow_redirects=False)

    assert response.status_code == 200, "the entry point must not redirect"
    assert "text/html" in response.headers["content-type"]
    assert '<div id="root">' in response.text
    assert "<title>Ztockz" in response.text
    assert "/ui/app.js" not in response.text


def test_built_html_references_only_the_app_base() -> None:
    html = INDEX.read_text(encoding="utf-8")
    urls = re.findall(r'(?:src|href)="(/[^"]+)"', html)
    asset_urls = [url for url in urls if "/assets/" in url]

    assert asset_urls, "the build declares no assets"
    assert all(url.startswith("/app/assets/") for url in asset_urls), asset_urls
    # The classic Vite-behind-a-subpath bug: an asset URL rooted at "/" is
    # reachable in dev and 404 in production.
    assert not [url for url in urls if url.startswith("/assets/")]


def test_entry_assets_load_under_the_app_base(client: TestClient) -> None:
    html = _index(client)
    urls = _initial_js_urls(html)
    assert urls, "index.html declares no initial script"

    css_urls = re.findall(r'<link[^>]+rel="stylesheet"[^>]+href="([^"]+\.css)"', html)
    assert css_urls, "index.html declares no stylesheet"

    for url in urls:
        response = client.get(url)
        assert response.status_code == 200, url
        assert "javascript" in response.headers["content-type"], url
        assert len(response.content) > 1_000, url

    for url in css_urls:
        response = client.get(url)
        assert response.status_code == 200, url
        assert "text/css" in response.headers["content-type"], url
        # The token block must have survived the Tailwind pass.
        assert "--row-bg" in response.text


def test_deep_link_returns_the_same_document(client: TestClient) -> None:
    shell = _index(client)
    for path in ("/app/screener/value", "/app/value/AAPL", "/app/settings/theme"):
        response = client.get(path)
        assert response.status_code == 200, path
        assert "text/html" in response.headers["content-type"], path
        assert response.text == shell, f"{path} did not return the built index.html"


def test_hard_refresh_on_a_deep_link_still_loads_every_asset(client: TestClient) -> None:
    """The deep link's own HTML must point at assets that resolve.

    This is the end-to-end version of the base-path check: a refresh on
    ``/app/value/AAPL`` serves index.html, and the asset URLs *inside that
    response* are fetched exactly as a browser would.
    """

    deep = client.get("/app/value/AAPL")
    assert deep.status_code == 200
    urls = _initial_js_urls(deep.text) + re.findall(
        r'<link[^>]+rel="stylesheet"[^>]+href="([^"]+\.css)"', deep.text
    )
    assert urls
    for url in urls:
        assert client.get(url).status_code == 200, url


