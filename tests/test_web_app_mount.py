#: 180 KB, the Phase 1 gate (plan §3). Binary kilobytes: the budget is a byte
#: count, and 180 × 1000 would quietly hand back 3 % of headroom.
JS_BUDGET_BYTES = 180 * 1024


@pytest.fixture(scope="module")
def client() -> TestClient:
    return TestClient(create_app())


def _index(client: TestClient) -> str:
    response = client.get("/app")
    assert response.status_code == 200
    return response.text


def _initial_js_urls(html: str) -> list[str]:
    """Scripts and modulepreloads the browser must fetch before first paint."""

    scripts = re.findall(r'<script[^>]+src="([^"]+\.js)"', html)
    preloads = re.findall(r'<link[^>]+rel="modulepreload"[^>]+href="([^"]+\.js)"', html)
    return scripts + preloads


def _asgi_get(app: Any, path: str) -> tuple[int, dict[str, str], bytes]:
    """One GET through the ASGI app with ``path`` exactly as given.

    ``httpx`` normalises ``..`` before the request leaves the client, so a
    TestClient call cannot prove what the *server* does with a traversal path.
    This harness builds the scope by hand — the same bytes uvicorn would hand
    the app after percent-decoding — and is the only honest way to test it.
    """

    scope = {
        "type": "http",
        "asgi": {"version": "3.0", "spec_version": "2.3"},
        "http_version": "1.1",
        "method": "GET",
        "scheme": "http",
        "path": path,
        "raw_path": path.encode("latin-1"),
        "root_path": "",
        "query_string": b"",
        "headers": [(b"host", b"testserver")],
        "server": ("testserver", 80),
        "client": ("127.0.0.1", 12345),
    }
    status = 0
    headers: dict[str, str] = {}
    body = bytearray()
    calls = 0

    async def receive() -> dict[str, Any]:
        # The request, then a client that keeps the connection open while the
        # body streams. ``FileResponse`` (Starlette 2.3 scopes) runs a task
        # group that watches ``receive`` for a disconnect and aborts the body
        # when it sees one — so answering ``http.disconnect`` here truncates a
        # 200 to zero bytes, and never answering at all leaves the body pending
        # (the first version of this harness hung on every 200).
        nonlocal calls
        calls += 1
        if calls > 1:
            await asyncio.Event().wait()
        return {"type": "http.request", "body": b"", "more_body": False}

    async def send(message: dict[str, Any]) -> None:
        nonlocal status
        if message["type"] == "http.response.start":
            status = int(message["status"])
            headers.update(
                {
                    key.decode("latin-1").lower(): value.decode("latin-1")
                    for key, value in message.get("headers", [])
                }
            )
        elif message["type"] == "http.response.body":
            body.extend(message.get("body", b""))

    asyncio.run(app(scope, receive, send))
    return status, headers, bytes(body)


