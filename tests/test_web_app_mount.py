"""The React interface is served at ``/app``; the old cockpit at ``/`` and ``/ui/`` does not move.

Three classes of assertion live here, and they are deliberately separate:

* **Delivery** — the shell, its assets, and a deep link all answer 200 with the
  right bytes, under the ``/app/`` base Vite was built with. A base-path bug is
  invisible in ``npm run build`` and fatal in a browser, so it is asserted from
  the built HTML outwards.
* **Containment** — the mount cannot be walked out of, a missing asset is not
  masked by the SPA fallback, and ``/app/api/…`` fails as JSON rather than
  rendering a shell. Each of these is a real failure mode of "serve a SPA with
  StaticFiles", not a hypothetical.
* **Budget** — the initial JS is measured from the artefact with an independent
  gzip pass, and the node gate is proven to fail when its budget is lowered.

Everything skips when ``web/dist`` is absent: the artefact is generated by
``npm run build`` and is not committed, so a source-only checkout must not fail
on a file it was never given.
"""

from __future__ import annotations

import asyncio
import gzip
