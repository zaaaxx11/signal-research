def test_directory_traversal_is_refused_at_the_asgi_layer() -> None:
    """``..`` in the scope path must never read a file outside web/dist.

    The canary is the application's own source: a successful escape would put
    ``create_app`` or ``from __future__`` in the body.
    """

    app = create_app()
    traversals = [
        "/app/../app/main.py",
        "/app/../../app/main.py",
        "/app/%2e%2e/app/main.py",
        "/app/..%2fapp/main.py",
        "/app/assets/../../../app/main.py",
        "/app/assets/../../../../etc/passwd",
    ]

    for path in traversals:
        status, headers, body = _asgi_get(app, path)
        assert status in {400, 403, 404}, f"{path} -> {status}"
        assert b"create_app" not in body, path
        assert b"from __future__" not in body, path
        assert b"root:x:" not in body, path
        assert "text/html" not in headers.get("content-type", ""), path


def test_static_lookup_refuses_paths_that_leave_the_directory() -> None:
    """The guard inside Starlette, asserted directly.

    ``StaticFiles.lookup_path`` resolves with ``realpath`` and compares common
    paths; a relative path that climbs out returns no file rather than the
    target. Proving it here means the HTTP-level assertions above are not
    passing only because routing rejected the URL first.
    """

    spa = _SpaStaticFiles(directory=DIST, html=True)

    assert spa.lookup_path("../app/main.py") == ("", None)
    assert spa.lookup_path("../../README.md") == ("", None)
    assert spa.lookup_path("/etc/passwd") == ("", None)
    assert spa.lookup_path("index.html")[1] is not None


#: The auditor's exact reproductions (``research/phase1-adversarial.md`` §F2).
#: Every one of these answered ``200 text/html`` before the fallback tightened:
#: a blocked escape was dressed as a client route, so a monitor watching status
#: codes could not tell an attack from a page view.
#:
#: The scope carries the path *as the server hands it to the app* — uvicorn
#: decodes the URL once — so the double-encoded form appears both as written on
#: the wire and as it arrives at the ASGI scope. ``get_path`` collapses literal
#: ``//`` and ``..`` before the fallback sees ``path``, which is exactly why the
#: decision is taken on the raw scope path instead.
REFUSED_PATHS = (
    "/app//etc/passwd",
    "/app///etc/passwd",
    "/app/%252e%252e%252f%252e%252e%252fetc%252fpasswd",
    "/app/%2e%2e%2f%2e%2e%2fetc%2fpasswd",
    "/app/x%00",
    "/app/x\x00",
    "/app/%00",
    "/app/\x00",
    "/app/assets",
    "/app/assets/",
    "/app/.git/config",
    "/app/.env",
    "/app/HEALTH",
    "/app/Screens/select",
    "/app/./value/AAPL",
    "/app/value/../../etc/passwd",
)


def test_traversal_shaped_paths_are_refused_with_json() -> None:
    """A refused shape must be a 404 the operator can see, not a 200 shell.

    A 200 here is indistinguishable from a real client route: the block happens,
    but nothing in the status code or the body says so, and the only trace is a
    missing log line nobody wrote. Each of these is 404 JSON, and none of them
    can carry the shell.
    """

    app = create_app()

    for path in REFUSED_PATHS:
        status, headers, body = _asgi_get(app, path)
        assert status == 404, f"{path} -> {status} {body[:120]!r}"
        assert "application/json" in headers.get("content-type", ""), path
        assert b"<!doctype" not in body.lower(), path
        assert b'<div id="root">' not in body, path
        assert body, f"{path} answered an empty 404"


def test_reserved_segments_are_matched_case_insensitively() -> None:
    """``/app/HEALTH`` and ``/app/health`` name the same API namespace.

    A case-sensitive comparison made one a client route and the other a 404,
    which is a coin flip an attacker does not have to guess twice.
    """

    spa = _SpaStaticFiles(directory=DIST, html=True)

    for path in ("HEALTH", "Health", "screens/select", "Symbols/search", "ASSETS/i.js"):
        assert spa._is_client_route(path) is False, path
    # The reservation is a first-segment rule, not a substring ban.
    assert spa._is_client_route("settings/health") is True


