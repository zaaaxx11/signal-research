def test_initial_js_is_within_the_180_kb_gzip_budget() -> None:
    """Independent of scripts/check-budget.mjs: the test re-measures the artefact."""

    html = INDEX.read_text(encoding="utf-8")
    urls = _initial_js_urls(html)
    assert urls, "index.html declares no initial script"

    total_raw = 0
    total_gzip = 0
    sizes: list[str] = []
    for url in urls:
        relative = url.split("/app/", 1)[-1]
        path = DIST / relative
        assert path.is_file(), url
        payload = path.read_bytes()
        compressed = len(gzip.compress(payload, compresslevel=9))
        total_raw += len(payload)
        total_gzip += compressed
        sizes.append(f"{path.name}: {len(payload)} B raw / {compressed} B gz")

    print("\ninitial JS — " + "; ".join(sizes))
    print(f"total {total_raw} B raw / {total_gzip} B gzip")

    assert total_gzip <= JS_BUDGET_BYTES, (
        f"initial JS is {total_gzip} B gzip, budget is {JS_BUDGET_BYTES} B"
    )


def test_budget_script_is_wired_into_check_and_fails_when_lowered() -> None:
    node = shutil.which("node") or ""
    if not node:
        pytest.skip("node is not installed")

    package = json.loads((WEB_DIR / "package.json").read_text(encoding="utf-8"))
    # check -> budget -> the file. Each hop asserted, so a rename breaks here
    # rather than silently removing the gate from `npm run check`.
    assert "npm run budget" in package["scripts"]["check"]
    assert "check-budget.mjs" in package["scripts"]["budget"]
    assert package["scripts"]["build"].startswith("tsc --noEmit && vite build")

    passing = subprocess.run(
        [node, "scripts/check-budget.mjs"],
        cwd=WEB_DIR,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert passing.returncode == 0, passing.stderr
    assert "initial total" in passing.stdout

    # The gate must bite: the same artefact against a 1 KB budget has to fail.
    failing = subprocess.run(
        [node, "scripts/check-budget.mjs", "--budget-kb=1"],
        cwd=WEB_DIR,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert failing.returncode == 1, failing.stdout + failing.stderr
    assert "exceeds the 1 KB budget" in failing.stderr


def test_shell_has_no_third_party_origins() -> None:
    """No CDN, no analytics, no hosted font: the document is self-contained."""

    html = INDEX.read_text(encoding="utf-8")
    assert "http://" not in html
    assert "https://" not in html
    assert "//cdn" not in html
    assert "@import url(" not in html

    for css in (DIST / "assets").glob("*.css"):
        text = css.read_text(encoding="utf-8")
        assert "@import url(" not in text, css.name
        assert "url(http" not in text, css.name

    # Exactly one module in the source may call fetch, and it is the API client.
    callers = sorted(
        path.name
        for path in (WEB_DIR / "src").rglob("*")
        if path.suffix in {".ts", ".tsx"}
        and ".test." not in path.name
        and re.search(r"\bfetch\(", path.read_text(encoding="utf-8"))
    )
    assert callers == ["api.ts"], callers
