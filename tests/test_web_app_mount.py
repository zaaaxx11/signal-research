def test_missing_asset_is_not_masked_by_the_spa_fallback(client: TestClient) -> None:
    """A wrong chunk URL must 404, not return HTML with a 200.

    If the fallback answered this with index.html the browser would try to
    execute HTML as JavaScript and report ``Unexpected token '<'`` — an error
    two layers away from the actual cause.
    """

    for path in ("/app/assets/index-DOES-NOT-EXIST.js", "/app/assets/nope.css"):
        response = client.get(path)
        assert response.status_code == 404, path
        assert "<!doctype html" not in response.text.lower(), path


def test_reserved_api_prefix_fails_as_json_not_as_a_shell(
    client: TestClient,
) -> None:
    """No API lives under /app, so a call there is a client bug and must say so.

    The two failures this prevents are the same bug with different spellings:
    a fetch to the wrong base, and a root API namespace re-used as a client
    route. Both must answer 404 JSON, never a 200 shell.
    """

    for path in (
        "/app/api/nope",
        "/app/screens/select",
        "/app/health",
        "/app/symbols/search",
    ):
        response = client.get(path)
        assert response.status_code == 404, path
        assert "application/json" in response.headers["content-type"], path
        assert "<!doctype html" not in response.text.lower(), path
        assert "Not Found" in response.text, path


