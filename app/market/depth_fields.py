"""The 116-column screener catalog as a registry, not a comment.

A depth row may only publish a name that the catalog declares. That rule used to
live in prose ("field hanya boleh dari daftar katalog"); here it is data:

* :data:`FIELD_SPECS` — one :class:`FieldSpec` per catalog column, generated
  from ``app/engine/data/finviz_columns_116.json`` at import time. The catalog
  stays the single source of truth for *names and units*; this module adds the
  three things the catalog does not carry: which source is expected to fill the
  cell (``owner``), how faithful that fill is to the Finviz definition
  (``quality``) and, for derived cells, the formula.
* :func:`field_spec` — the lookup the depth sources and the API use to answer
  "is this a real column, and who owns it?".
* :func:`is_catalog_field` — the cheap membership guard used when projecting a
  provider payload.

Ownership vocabulary (``owner``)
--------------------------------
``yahoo``     Yahoo Finance, the primary depth source in this phase.
``finra``     FINRA consolidated short interest — the product decision is that
              ``short_interest`` is *not* taken from Yahoo, whose ``sharesShort``
              is a point-in-time share count with a different settlement date.
``quote``     The realtime quote hub. Price, change, volume and previous close
              must never live in the depth store, or two stores would publish
              two prices for one symbol.
``product``   Generated by the product, not fetched from a provider.
``screener``  Screener bookkeeping, not market data.

Quality vocabulary (``quality``)
--------------------------------
``exact``       Same definition as the Finviz cell; a drop-in replacement.
``equivalent``  Same metric, slightly different estimator or basis; usable with
                a note (the research doc's verdict **B**).
``definition``  The cell is filled but the number means something else (verdict
                **C**). It may be published only with a definition label.
``proxy``       Computed with an estimator Finviz does not document.
``missing``     The owner cannot supply it; the cell stays empty rather than
                being filled with a lookalike.

``missing`` is therefore a statement about the *owner*, not about the catalog:
``eps_past_5y`` is owned by Yahoo (nobody else is configured) and Yahoo stopped
shipping the ``-5y`` estimate period, so the cell is empty by fact, not by
omission.

The registry is import-time validated: a catalog column with no ownership entry
raises, and an ownership entry with no catalog column raises. A renamed column
must be classified deliberately instead of silently becoming "unknown".
"""

