#: The catalog's printed unit is a display hint, not always the stored unit.
#: Finviz prints these two as a distance in percent, but every consumer (and the
#: quote page) uses the dollar level, so the catalog entry is corrected here
#: rather than in the read-only JSON.
_UNIT_OVERRIDES: dict[str, str] = {
    "high_52w": "USD",
    "low_52w": "USD",
    "all_time_high": "USD",
    "all_time_low": "USD",
}


@lru_cache(maxsize=1)
def _catalog_rows() -> tuple[dict[str, object], ...]:
    payload = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    if not isinstance(payload, list):
        raise RuntimeError(f"{CATALOG_PATH} must contain a JSON list of columns")
    rows: list[dict[str, object]] = []
    for entry in payload:
        if not isinstance(entry, dict) or not str(entry.get("key") or "").strip():
            raise RuntimeError(f"{CATALOG_PATH} carries a column without a key")
        rows.append(entry)
    return tuple(rows)


def _build_specs() -> dict[str, FieldSpec]:
    specs: dict[str, FieldSpec] = {}
    for row in _catalog_rows():
        name = str(row["key"]).strip()
        ownership = _OWNERSHIP.get(name)
        if ownership is None:
            raise RuntimeError(
                f"catalog column {name!r} has no ownership entry in depth_fields; "
                "classify it before publishing it"
            )
        owner, quality = ownership
        specs[name] = FieldSpec(
            name=name,
            owner=owner,
            quality=quality,
            unit=_UNIT_OVERRIDES.get(name, str(row.get("unit") or "unknown")),
            formula=_FORMULAS.get(name),
        )
    unknown = sorted(set(_OWNERSHIP) - set(specs))
    if unknown:
        raise RuntimeError(
            f"depth_fields classifies columns the catalog does not declare: {unknown}"
        )
    return specs


#: ``name -> FieldSpec`` for exactly the 116 catalog columns.
FIELD_SPECS: dict[str, FieldSpec] = _build_specs()

#: Membership guard for projecting a provider payload onto the catalog.
CATALOG_FIELDS: frozenset[str] = frozenset(FIELD_SPECS)


def field_spec(name: str) -> FieldSpec | None:
    """The spec for a catalog column, or ``None`` for a foreign name.

    Returning ``None`` (rather than raising) is deliberate: the callers are
    parsing untrusted provider payloads, where "this key is not a column" is an
    ordinary answer and not a crash.
    """

    return FIELD_SPECS.get(str(name or "").strip())


def is_catalog_field(name: str) -> bool:
    return str(name or "").strip() in FIELD_SPECS


def field_names() -> tuple[str, ...]:
    """The 116 names in catalog order."""

    return tuple(str(row["key"]).strip() for row in _catalog_rows())


